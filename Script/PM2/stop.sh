#!/bin/bash
# ============================================================
# MonGSV 停止脚本 (PM2)
# ============================================================
set -e

PM2="$(command -v pm2 2>/dev/null || echo 'npx pm2')"

if ! $PM2 --version &>/dev/null; then
    echo "[错误] pm2 未安装，请执行: npm install -g pm2"
    exit 1
fi

echo "============================================================"
echo "  MonGSV - 停止服务"
echo "============================================================"

$PM2 stop all

echo ""
$PM2 status
echo ""
echo "[完成] 服务已停止"
